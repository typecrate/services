//! Rendering the generated module, and writing it without disturbing cargo's fingerprint.
//!
//! The emitted file is deliberately plain: absolute `#[path]` module declarations plus two
//! chaining functions - `register_routes` (the router) and `route_metadata` (R3, the
//! discovered-endpoint listing). Everything else (extractors, state, error handling) is
//! ordinary axum in the route file, so a broken route fails as a normal rustc error that
//! points at the route file itself - never as a runtime registry lookup.
//!
//! The generator never reads a route file's *contents*: each route file declares its
//! endpoints through `crate::service_routes!` (`src/server/metadata.rs`), which emits that
//! module's `register` fn and its `pub const ENDPOINTS` from one entry list. This file only
//! has to chain the modules and name their `ENDPOINTS` in the same order, which is what
//! makes "what is mounted" and "what is listed" the same truth by construction (R3) - a
//! source-parsing scanner here could report a method the router does not serve.
//!
//! Comments are `//`, never `//!`: the host includes this file with `include!`, and inner
//! doc comments are only legal at the very start of a module body.

use std::fs;
use std::path::Path;

use super::GENERATED_FUNCTION;
use super::GENERATED_METADATA_FUNCTION;
use super::ROUTE_ENDPOINTS_CONST;
use super::naming;
use super::types::ScanReport;

/// Header emitted above the module declarations (no timestamp: the file must be
/// byte-stable for a byte-stable tree, which is what `tests/discovery.rs` asserts).
fn header(report: &ScanReport) -> String {
    let mut lines: Vec<String> = vec![
        "// Generated by `build.rs` of the `typecrate-services` package - DO NOT EDIT.".to_owned(),
        "//".to_owned(),
        "// Build-time service-route registration module. Include it at CRATE SCOPE, exactly"
            .to_owned(),
        "// as `src/lib.rs` does - the signatures below already name".to_owned(),
        "// `crate::server::AppState`, so the crate root is the one place the include and the"
            .to_owned(),
        "// `crate::register_routes` call in `src/server/mod.rs` cannot drift apart:".to_owned(),
        "//     include!(concat!(env!(\"OUT_DIR\"), \"/service_routes.rs\"));".to_owned(),
        "//".to_owned(),
        format!("// Scan root: {}", report.root.display()),
        format!("// Routes found: {}", report.routes.len()),
        "//".to_owned(),
        "// Registration order is the scanner's deterministic order: byte-wise comparison of the"
            .to_owned(),
        "// scan-root-relative path. Re-scanning the same tree reproduces this file byte for byte."
            .to_owned(),
        "//".to_owned(),
        "// Each route file declares its endpoints with `crate::service_routes!`".to_owned(),
        "// (`src/server/metadata.rs`): that macro emits the module's `register` fn AND its"
            .to_owned(),
        "// `pub const ENDPOINTS` from the same entries. `route_metadata` below concatenates"
            .to_owned(),
        "// those slices in the order above, so the endpoint listing is the router - never a"
            .to_owned(),
        "// second table. Built-in routes in `src/server` are not part of it, and an".to_owned(),
        "// `EndpointMeta` row holds method/path/summary only: no scan root, no `#[path]`."
            .to_owned(),
    ];
    // The per-route map: what a reader of this file needs to connect a path on disk with the
    // identifier the declarations below use (and with `<identifier>::ENDPOINTS` in
    // `route_metadata`). Format asserted by `tests/discovery.rs`. Skipped for an empty tree,
    // where there is nothing to map (and `build.rs` warns about that case anyway).
    if !report.routes.is_empty() {
        lines.push("//".to_owned());
        lines.push("// Discovered route file -> generated module identifier:".to_owned());
    }
    for route in &report.routes {
        lines.push(format!(
            "//   {} -> mod {}",
            route.relative_path, route.module_name
        ));
    }
    let mut text = lines.join("\n");
    text.push('\n');
    text
}

/// Renders the whole generated module for `report`.
#[must_use]
pub fn generate_module(report: &ScanReport) -> String {
    let mut generated = header(report);
    generated.push('\n');

    // One module per route file. The `#[path]` value is absolute, so the module resolves
    // from any crate that includes this file; `escape_debug` turns a Windows `\` into the
    // `\\` the string literal needs (and escapes quotes/control characters, which are the
    // only other characters a path can carry that would break a literal).
    for route in &report.routes {
        let path_literal = format!("\"{}\"", route.path.display().to_string().escape_debug());
        // F2: a digit-leading or capitalised path segment sanitises into an identifier that
        // is valid but not snake case (`endpoints/2024/` -> `endpoints__2024_service_route`),
        // and the generated file is linted like hand-written code. The attribute is emitted
        // only for those identifiers - see `naming::needs_snake_case_allow` for the measured
        // rule and for why it rides along to the module body.
        let allow = if naming::needs_snake_case_allow(&route.module_name) {
            "#[allow(non_snake_case)]\n"
        } else {
            ""
        };
        generated.push_str(&format!(
            "{allow}#[path = {path_literal}]\nmod {module_name};\n\n",
            module_name = route.module_name
        ));
    }
    generated.push_str(
        "/// Registers every discovered service route onto `router`, in the order listed above.\n",
    );
    // Split rather than one big literal: a multi-line literal would need `\<space>`
    // gymnastics to keep the 4-space indentation after a line continuation.
    generated.push_str("pub fn ");
    generated.push_str(GENERATED_FUNCTION);
    generated.push_str("(\n    router: axum::Router<crate::server::AppState>,\n) -> axum::Router<crate::server::AppState> {\n");

    // The chain ends with a CALL, not with a bare binding. `let router = ...; router` is
    // `clippy::let_and_return`, and the generated file is `include!`d into the crate, so
    // `npm run lint:strict` (`-D warnings`) lints it like any hand-written line. Binding
    // every route except the last keeps the chain readable and the semantics identical
    // (`b(a(router))` == `let router = a(router); b(router)`).
    let last = report.routes.len();
    for (index, route) in report.routes.iter().enumerate() {
        if index + 1 == last {
            generated.push_str(&format!("    {}::register(router)\n", route.module_name));
        } else {
            generated.push_str(&format!(
                "    let router = {}::register(router);\n",
                route.module_name
            ));
        }
    }
    // With zero routes the body is just the identity, which keeps the host compiling
    // (an empty tree is legal; `build.rs` warns about it instead). `router` here is the
    // PARAMETER, so the let_and_return lint above cannot fire.
    if last == 0 {
        generated.push_str("    router\n");
    }
    generated.push_str("}\n");

    // ------------------------------------------------------------------
    // R3: the discovered-endpoint listing, generated at the SAME crate scope from the
    // SAME module list, so "what is mounted" and "what is listed" are one truth.
    //
    // Why this shape (each part is load-bearing):
    //   * the method/path/summary values are not rendered here at all - they live in each
    //     module's `ENDPOINTS` const, which `crate::service_routes!` emits from the very
    //     tokens `register` above mounts (`src/server/metadata.rs`). This generator reads no
    //     route-file *contents*, so there is nothing to parse wrongly and nothing to drift;
    //   * a `&[&[EndpointMeta]]` const pins the order here (registration order) and keeps the
    //     data `&'static`: no runtime registry, no mutable global, nothing to observe
    //     half-updated;
    //   * `[&[T]]::concat` (stable, needs only `T: Clone`) flattens it into the owned `Vec`
    //     the playground serialises;
    //   * the empty list is legal: the const's type annotation gives `&[]` its element type,
    //     and `concat()` then returns an empty `Vec`, so a zero-route tree still compiles the
    //     whole surface;
    //   * no `#[allow(non_snake_case)]` is needed around the references below even when a
    //     module identifier is `endpoints__2024_service_route` or `endpoints_Unicode_...`:
    //     rustc reports that lint at the `mod` DEFINITION (the F2 note above), never at a use
    //     path, and `route_metadata`/`DISCOVERED` are themselves snake case.
    generated.push('\n');
    generated
        .push_str("/// Metadata for every discovered service route, in the order listed above.\n");
    generated.push_str("///\n");
    generated.push_str(
        "/// Built-ins (`src/server`) are deliberately absent: this is the *discovered*\n",
    );
    generated
        .push_str("/// endpoint listing, and every row comes from the entries that module's\n");
    generated.push_str(
        "/// `crate::service_routes!` invocation already mounted, so it cannot disagree\n",
    );
    generated.push_str("/// with `register_routes` above.\n");
    generated.push_str("pub fn ");
    generated.push_str(GENERATED_METADATA_FUNCTION);
    generated.push_str("() -> Vec<crate::server::EndpointMeta> {\n");
    generated.push_str("    // `ENDPOINTS` of every discovered module, in registration order.\n");
    generated.push_str("    const DISCOVERED: &[&[crate::server::EndpointMeta]] = &[\n");
    // No `for`-index special case: zero iterations leaves `&[`, `\n`, `];` behind, which is
    // an empty array literal, exactly the identity this function needs for an empty tree.
    for route in &report.routes {
        generated.push_str(&format!(
            "        {module}::{endpoints},\n",
            module = route.module_name,
            endpoints = ROUTE_ENDPOINTS_CONST
        ));
    }
    generated.push_str("    ];\n");
    generated.push_str("    DISCOVERED.concat()\n");
    generated.push_str("}\n");
    generated
}

/// Writes `content` to `path` only when the bytes actually differ, returning whether a
/// write happened.
///
/// The host `include!`s this file, so rewriting identical bytes would bump the OUT_DIR
/// mtime and recompile the crate on every single build.
///
/// # Errors
///
/// A one-line, actionable message for the two I/O failures that matter (cannot create the
/// output directory, cannot write the file).
pub fn write_generated_if_changed(path: &Path, content: &str) -> Result<bool, String> {
    // Let-chain (edition 2024): an existing file with identical bytes is the no-op case.
    if let Ok(existing) = fs::read_to_string(path)
        && existing == content
    {
        return Ok(false);
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .map_err(|err| format!("could not create `{}`: {err}", parent.display()))?;
    }
    fs::write(path, content)
        .map_err(|err| format!("could not write `{}`: {err}", path.display()))?;
    Ok(true)
}
